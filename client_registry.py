"""Persistent OAuth public-client registration with redirect URI allowlisting.

Registration does not authorize access. Owner approval and PKCE remain required.
"""
import json
import secrets
import sqlite3
from pathlib import Path
from urllib.parse import urlsplit

def valid_redirect(uri: str) -> bool:
    try:
        parts = urlsplit(uri)
        if parts.fragment or parts.username or parts.password:
            return False
        if parts.scheme == "https" and parts.hostname:
            return True
        if parts.scheme == "http" and parts.hostname in ("127.0.0.1", "::1", "localhost"):
            return True
        return False
    except ValueError:
        return False

class ClientRegistry:
    def __init__(self, path: str):
        self.path = path
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        with sqlite3.connect(path) as db:
            db.execute("""CREATE TABLE IF NOT EXISTS oauth_clients(
                client_id TEXT PRIMARY KEY, name TEXT NOT NULL,
                redirect_uris TEXT NOT NULL, revoked INTEGER NOT NULL DEFAULT 0
            )""")

    def register(self, name: str, redirect_uris: list[str]) -> str:
        if not 1 <= len(name) <= 100 or not 1 <= len(redirect_uris) <= 10:
            raise ValueError("invalid client metadata")
        if len(set(redirect_uris)) != len(redirect_uris) or not all(valid_redirect(u) for u in redirect_uris):
            raise ValueError("invalid redirect URI")
        client_id = secrets.token_urlsafe(24)
        with sqlite3.connect(self.path) as db:
            db.execute("INSERT INTO oauth_clients VALUES (?,?,?,0)",
                       (client_id, name, json.dumps(redirect_uris)))
        return client_id

    def allowed(self, client_id: str, redirect_uri: str) -> bool:
        with sqlite3.connect(self.path) as db:
            row = db.execute("SELECT redirect_uris,revoked FROM oauth_clients WHERE client_id=?",
                             (client_id,)).fetchone()
        return bool(row and not row[1] and redirect_uri in json.loads(row[0]))

    def revoke(self, client_id: str) -> None:
        with sqlite3.connect(self.path) as db:
            db.execute("UPDATE oauth_clients SET revoked=1 WHERE client_id=?", (client_id,))

    def register_external(self, client_id: str, name: str, redirect_uris: list[str]) -> None:
        """Persist a client identifier generated by the OAuth SDK."""
        if not client_id or len(client_id) > 256:
            raise ValueError("invalid client ID")
        if not 1 <= len(name) <= 100 or not 1 <= len(redirect_uris) <= 10:
            raise ValueError("invalid client metadata")
        if len(set(redirect_uris)) != len(redirect_uris) or not all(valid_redirect(u) for u in redirect_uris):
            raise ValueError("invalid redirect URI")
        with sqlite3.connect(self.path) as db:
            db.execute("INSERT INTO oauth_clients VALUES (?,?,?,0)",
                       (client_id, name, json.dumps(redirect_uris)))
